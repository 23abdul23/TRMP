"""Generate thesis/Appendices/AppendixB.tex (per-instance full-protocol results) from out/full_block/*.row
and the reference table results_ESapproach.ods. Run from the project root with the venv python."""
import glob, os, re
import pandas as pd, numpy as np
ref = pd.read_excel('results_ESapproach.ods', engine='odf', sheet_name='Sheet1')
ref.columns = ['inst','n','best','avg','sd','time','sdtime','bg','sbg']; ref['inst'] = ref.inst.str.replace('.dat','',regex=False)
rows=[]
for f in sorted(glob.glob('out/full_block/*.row')):
    t=open(f).read().split()
    rows.append(dict(inst=os.path.basename(t[0]).replace('.dat',''),best_b=float(t[2]),avg_b=float(t[3]),sd_b=float(t[4])))
d=pd.DataFrame(rows).merge(ref,on='inst'); assert len(d)==60, len(d)
d['ap']=d.inst.str.extract(r's(0[346])i')[0].map({'03':r'$2\pi/3$','04':r'$\pi/2$','06':r'$\pi/3$'})
d['short']=d.inst.str.extract(r'm(\d{3})m\d+r150(s0\d)(i\d\d)').apply(lambda r:f"{int(r[0])}-{r[1]}-{r[2]}" if False else None,axis=1)
def short(s):
    m=re.search(r'dirn(\d{3})m\d+r150s(0\d)i(\d\d)',s); return f"m{int(m.group(1))}-s{m.group(2)}-i{m.group(3)}"
d['short']=d.inst.map(short)
d['dm']=100*(d.avg_b-d.avg)/d.avg; d['db']=100*(d.best_b-d.best)/d.best
d=d.sort_values(['n','inst']).reset_index(drop=True)
def pct(x):
    s=f"{x:+.2f}".replace('-','$-$').replace('+','$+$'); return s if abs(x)>=0.005 else '0.00'
L=[]
L.append(r"% Appendix B -- generated by scripts/make_thesis_tables.py from out/full_block/*.row; do not edit by hand")
L.append(r"\chapter{Per-Instance Results of the Full Protocol}\label{AppendixB}")
L.append(r"Table~\ref{tab:fullinst} lists, for each of the 60 benchmark instances, the published ES-TRMP result and the result with the contiguous (\texttt{block}) destroy at $\kappa=4$ under the paper's protocol (4{,}000 iterations, 20 runs, seeds $1,\ldots,20$). Mean is the average over 20 runs and Best the best of 20 (radians); the change is relative to ES-TRMP and negative is better. Instance names are abbreviated: \texttt{m400-s06-i02} is \texttt{covers\_dirn400m240r150s06i02}; \texttt{s03}, \texttt{s04}, \texttt{s06} are the sensing angles $2\pi/3$, $\pi/2$, $\pi/3$.")
L.append(r"{\footnotesize")
L.append(r"\setlength{\tabcolsep}{3.5pt}")
L.append(r"\begin{longtable}{lrcrrrrrr}")
L.append(r"\caption{Per-instance results, ES-TRMP (published) against ES-TRMP with contiguous destroy.}\label{tab:fullinst}\\")
L.append(r"\toprule \textbf{Instance} & $n$ & $\varphi$ & \textbf{ES mean} & \textbf{Block mean} & \textbf{Chg.\ \%} & \textbf{ES best} & \textbf{Block best} & \textbf{Chg.\ \%}\\ \midrule \endfirsthead")
L.append(r"\toprule \textbf{Instance} & $n$ & $\varphi$ & \textbf{ES mean} & \textbf{Block mean} & \textbf{Chg.\ \%} & \textbf{ES best} & \textbf{Block best} & \textbf{Chg.\ \%}\\ \midrule \endhead")
L.append(r"\bottomrule \endfoot")
for _,r in d.iterrows():
    L.append(f"\\texttt{{{r.short}}} & {int(r.n)} & {r.ap} & {r.avg:.3f} & {r.avg_b:.3f} & {pct(r.dm)} & {r.best:.3f} & {r.best_b:.3f} & {pct(r.db)}\\\\")
L.append(r"\end{longtable}")
L.append("}")
open('thesis/Appendices/AppendixB.tex','w').write("\n".join(L)+"\n")
print('wrote',len(d),'rows; mean dm',round(d.dm.mean(),2), 'n>=198 mean', round(d[d.n>=198].dm.mean(),2))
